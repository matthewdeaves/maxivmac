"""Emit the emulator-script block that sets MacTCP's manual address.

usage: mactcp-config.py IP/PREFIX [--gateway GW] [--dns DNS --domain DOMAIN]

Same gestures as scripts/ping/mactcp-config.inc (which is the slirp 10.0.2.15/24
case), parameterised: the four address fields, the subnet slider (only /24 is
supported besides the class default; a class A address such as 10.x.y.z keeps
/8 when the slider is left alone), and an optional gateway and DNS.  Without a
gateway the field is left empty (a LAN with no router).  Run it after the
"mactcp-open" block and before "mactcp-close".  Coordinates are for the 512x342
Plus screen with the MacTCP "More..." dialog open (see mactcp-open.inc).
"""
import argparse, ipaddress, sys

DELETE = "key delete\n" * 6


def field(octet):
    return DELETE + 'type "%s"\n' % octet


def block(ip, prefix, gateway=None, dns=None, domain=None):
    ip = ipaddress.IPv4Address(ip)
    if prefix not in (8, 24):
        raise SystemExit("only /8 (class A default) and /24 are scripted, got /%d" % prefix)
    if ip.packed[0] >= 128:
        raise SystemExit("only class A addresses are scripted (the class default must be /8)")
    o = [str(b) for b in ip.packed]
    out = ["# --- MacTCP manual address %s/%d%s (generated by test/net/mactcp-config.py)\n"
           % (ip, prefix, ", gateway " + gateway if gateway else ", no gateway")]
    if prefix == 24:
        out.append("# subnet slider: /8 -> /24 (stepwise moves, the cursor lags a single drag)\n"
                   "mousedown 276 108\nwait for 1s\nmove 380 108\nwait for 1s\n")
        for x in range(381, 386):
            out.append("move %d 108\nwait for 700ms\n" % x)
        out.append('mouseup\nwait for 1s\nscreenshot "m3_slider"\n')
    # The class A dialog has three boxes: Net (8 bits), Subnet and Node.  With the
    # slider at /24 the subnet is 16 bits (octets 2-3 as one number) and the node 8;
    # at the default /8 there is no subnet and the node is the 24 low bits.
    if prefix == 24:
        boxes = [o[0], str(ip.packed[1] * 256 + ip.packed[2]), o[3]]
    else:
        boxes = [o[0], str(int.from_bytes(ip.packed[1:], "big"))]
    out.append("# IP address boxes: Net %s\nclick 320 172 hold 300ms\nwait for 1s\n" % " / ".join(boxes))
    out.append("key tab\nwait for 1s\n".join(field(b) for b in boxes) + "wait for 2s\n")
    if gateway:
        out.append("# Gateway\nclick 115 243 hold 300ms\nwait for 1s\n" + "key delete\n" * 20
                   + 'type "%s"\nwait for 1s\n' % gateway)
    if dns:
        out.append("# DNS\nclick 255 271 hold 300ms\nwait for 1s\ntype \"%s\"\nwait for 1s\n"
                   % (domain or "example.net")
                   + "click 360 271 hold 300ms\nwait for 1s\n" + "key delete\n" * 20
                   + 'type "%s"\nwait for 1s\nclick 437 271 hold 300ms\nwait for 2s\n' % dns)
    out.append('screenshot "m3_fields"\n'
               "# OK on More..., then the panel's close box (writes \"MacTCP Prep\")\n"
               'click 75 311 hold 300ms\nwait for 6s\nscreenshot "m4_ok"\n'
               'click 70 47 hold 300ms\nwait for 6s\nscreenshot "m4_closed"\n')
    return "".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("addr", help="IP/PREFIX, e.g. 10.88.0.20/24")
    ap.add_argument("--gateway")
    ap.add_argument("--dns")
    ap.add_argument("--domain")
    a = ap.parse_args(argv)
    ip, _, p = a.addr.partition("/")
    sys.stdout.write(block(ip, int(p or 24), a.gateway, a.dns, a.domain))


if __name__ == "__main__":
    main(sys.argv[1:])
